/**
 * Pure Native Jetpack Compose Markdown + Go Vector TeX Formula Viewer.
 * Renders SVG math boxes generated by Go `core/texmath` directly onto Android Bitmaps via AndroidSVG —
 * ZERO WebView dependency!
 */
@Composable
fun NativeMarkdownDocumentView(
    doc: CompiledMarkdownDoc,
    modifier: Modifier = Modifier
) {
    var paperLight by remember { mutableStateOf(true) }
    val bgOuter = if (paperLight) Color(0xFFF3F4F6) else Color(0xFF121316)
    val cardBg = if (paperLight) Color.White else Color(0xFF1B1D24)
    val textMain = if (paperLight) Color(0xFF111827) else Color(0xFFF3F4F6)
    val textSub = if (paperLight) Color(0xFF4B5563) else Color(0xFF9CA3AF)
    val ruleColor = if (paperLight) Color(0xFFE5E7EB) else Color(0xFF2D313E)

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(bgOuter)
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .background(Color(0xFF1B1C20))
                .padding(horizontal = 12.dp, vertical = 4.dp),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Box(
                    modifier = Modifier
                        .background(Color(0xFFF3F4F6), RoundedCornerShape(4.dp))
                        .padding(horizontal = 5.dp, vertical = 1.dp)
                ) {
                    Text(
                        text = "M↓",
                        color = Color(0xFF111827),
                        fontSize = 10.sp,
                        fontFamily = FontFamily.Monospace,
                        fontWeight = FontWeight.ExtraBold
                    )
                }
                Spacer(Modifier.width(8.dp))
                Text(
                    text = doc.title,
                    color = Color.White,
                    fontSize = 13.sp,
                    fontWeight = FontWeight.SemiBold
                )
            }
            TextButton(onClick = { paperLight = !paperLight }) {
                Text(
                    text = if (paperLight) "深色护眼" else "亮白纸张",
                    color = Color(0xFF93C5FD),
                    fontSize = 12.sp
                )
            }
        }

        Column(
            modifier = Modifier
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(12.dp)
        ) {
            Surface(
                shape = RoundedCornerShape(16.dp),
                color = cardBg,
                modifier = Modifier
                    .fillMaxWidth()
                    .border(1.dp, ruleColor, RoundedCornerShape(16.dp))
            ) {
                Column(modifier = Modifier.padding(18.dp)) {
                    for (blk in doc.blocks) {
                        when (blk.kind) {
                            "heading" -> {
                                val sz = when (blk.level) {
                                    1 -> 21.sp
                                    2 -> 17.sp
                                    else -> 15.sp
                                }
                                Spacer(Modifier.height(if (blk.level <= 2) 14.dp else 8.dp))
                                Text(
                                    text = blk.plainText,
                                    color = textMain,
                                    fontSize = sz,
                                    fontWeight = FontWeight.Bold
                                )
                                if (blk.level <= 2) {
                                    Spacer(Modifier.height(6.dp))
                                    HorizontalDivider(color = ruleColor)
                                }
                                Spacer(Modifier.height(8.dp))
                            }

                            "paragraph" -> {
                                Text(
                                    text = blk.plainText,
                                    color = textMain,
                                    fontSize = 14.sp,
                                    lineHeight = 22.sp,
                                    modifier = Modifier.padding(vertical = 4.dp)
                                )
                                if (blk.inlineMaths.isNotEmpty()) {
                                    Row(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .horizontalScroll(rememberScrollState())
                                            .padding(vertical = 4.dp),
                                        horizontalArrangement = Arrangement.spacedBy(10.dp),
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        for (im in blk.inlineMaths) {
                                            VectorFormulaSvgImage(
                                                math = im,
                                                inkHex = if (paperLight) "#111827" else "#F3F4F6"
                                            )
                                        }
                                    }
                                }
                            }

                            "math_block" -> {
                                blk.math?.let { m ->
                                    Box(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .horizontalScroll(rememberScrollState())
                                            .padding(vertical = 12.dp),
                                        contentAlignment = Alignment.Center
                                    ) {
                                        VectorFormulaSvgImage(
                                            math = m,
                                            inkHex = if (paperLight) "#111827" else "#F3F4F6"
                                        )
                                    }
                                }
                            }

                            "code_block" -> {
                                Box(
                                    modifier = Modifier
                                        .fillMaxWidth()
                                        .padding(vertical = 6.dp)
                                        .background(
                                            if (paperLight) Color(0xFFF8FAFC) else Color(0xFF12141C),
                                            RoundedCornerShape(10.dp)
                                        )
                                        .border(1.dp, ruleColor, RoundedCornerShape(10.dp))
                                        .horizontalScroll(rememberScrollState())
                                        .padding(12.dp)
                                ) {
                                    Text(
                                        text = blk.code,
                                        color = textMain,
                                        fontFamily = FontFamily.Monospace,
                                        fontSize = 12.sp,
                                        lineHeight = 18.sp
                                    )
                                }
                            }

                            "blockquote" -> {
                                Row(
                                    modifier = Modifier
                                        .fillMaxWidth()
                                        .padding(vertical = 6.dp)
                                        .background(
                                            if (paperLight) Color(0xFFF0F9FF) else Color(0xFF1E293B),
                                            RoundedCornerShape(8.dp)
                                        )
                                        .padding(12.dp)
                                ) {
                                    Text(
                                        text = blk.plainText,
                                        color = textSub,
                                        fontSize = 13.sp,
                                        lineHeight = 20.sp
                                    )
                                }
                            }

                            "list" -> {
                                Column(modifier = Modifier.padding(vertical = 4.dp)) {
                                    blk.listItems.forEachIndexed { idx, item ->
                                        Text(
                                            text = "• $item",
                                            color = textMain,
                                            fontSize = 14.sp,
                                            lineHeight = 21.sp,
                                            modifier = Modifier.padding(vertical = 2.dp)
                                        )
                                    }
                                }
                            }

                            "hr" -> {
                                HorizontalDivider(
                                    color = ruleColor,
                                    modifier = Modifier.padding(vertical = 12.dp)
                                )
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun VectorFormulaSvgImage(
    math: MarkdownMathBox,
    inkHex: String
) {
    val density = LocalDensity.current.density
    val bmp = remember(math.svg, inkHex, density) {
        renderSvgFormulaBitmap(math.svg, math.width, math.height, inkHex, density)
    }
    if (bmp != null) {
        Image(
            bitmap = bmp.asImageBitmap(),
            contentDescription = math.tex,
            modifier = Modifier
                .width(math.width.dp)
                .height(math.height.dp)
        )
    } else {
        Text(
            text = math.tex,
            fontFamily = FontFamily.Serif,
            fontSize = 15.sp,
            style = MaterialTheme.typography.bodyMedium
        )
    }
}

private fun renderSvgFormulaBitmap(
    rawSvg: String,
    widthDp: Float,
    heightDp: Float,
    inkHex: String,
    density: Float
): Bitmap? {
    return try {
        val coloredSvg = rawSvg.replace("currentColor", inkHex)
        val svg = SVG.getFromString(coloredSvg)
        val pxW = max(8, (widthDp * density).roundToInt())
        val pxH = max(8, (heightDp * density).roundToInt())
        svg.documentWidth = pxW.toFloat()
        svg.documentHeight = pxH.toFloat()
        val bitmap = Bitmap.createBitmap(pxW, pxH, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(bitmap)
        svg.renderToCanvas(canvas)
        bitmap
    } catch (_: Throwable) {
        null
    }
}
